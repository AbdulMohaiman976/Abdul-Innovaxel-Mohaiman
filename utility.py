def update_url(short_code, new_url):
    now = datetime.utcnow().isoformat()
    conn = sqlite3.connect("database.db")
    cur = conn.cursor()
    cur.execute("UPDATE urls SET url = ?, updatedAt = ? WHERE shortCode = ?",
                (new_url, now, short_code))
    conn.commit()
    updated = cur.rowcount
    conn.close()

    if updated:
        return {"message": "URL updated successfully"}
    else:
        return {"error": "Short code not found"}

