def get_original_url(short_code):
    conn = sqlite3.connect("database.db")
    cur = conn.cursor()

    cur.execute("SELECT id, url, shortCode, createdAt, updatedAt, accessCount FROM urls WHERE shortCode = ?", (short_code,))
    row = cur.fetchone()

    if row:
        # Update access count
        cur.execute("UPDATE urls SET accessCount = accessCount + 1 WHERE shortCode = ?", (short_code,))
        conn.commit()
        conn.close()

        return {
            "id": row[0],
            "url": row[1],
            "shortCode": row[2],
            "createdAt": row[3],
            "updatedAt": row[4],
            "accessCount": row[5] + 1  # incremented
        }
    else:
        conn.close()
        return {"error": "Short code not found"}

